export function useI18n() {
  function t(key: string): string {
    const m = msgs[key]
    if (!m) return key
    return m[locale.value] || m.en || key
  }

  function setLocale(l: string) {
    locale.value = l
    localStorage.setItem('hub-locale', l)
  }

  return { locale, t, setLocale }
}
